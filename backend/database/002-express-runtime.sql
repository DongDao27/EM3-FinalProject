CREATE TABLE IF NOT EXISTS em3_sessions (
 sid VARCHAR(128) PRIMARY KEY, user_id BIGINT UNSIGNED NULL, data JSON NOT NULL,
 expires_at DATETIME(6) NOT NULL, INDEX(expires_at), INDEX(user_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS em3_mail_jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, payload TEXT NOT NULL, attempts INT NOT NULL DEFAULT 0,
 available_at DATETIME(6) NOT NULL, locked_at DATETIME(6) NULL, completed_at DATETIME(6) NULL,
 failed_at DATETIME(6) NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX(available_at,completed_at)
) ENGINE=InnoDB;
